#!/usr/bin/env python3
"""Write the SQL that gives every municipality the standard report categories.

Until categories are routed separately, all of a municipality's categories go to its one general
address (email_recommended in dimoi_emails_official.csv). Municipalities with their own file in
data/greece/contacts/ (OWN_FILE below) are left to it.

Usage:
    dimoi-sql.py <dimoi_emails_official.csv> <output.sql> [<corrections.csv> ...]

corrections.csv: rows with name_el, email_recommended and email_source (e.g. an address a
municipality sent us with "MAIL ΔΗΜΟΥ:"); they replace the official list's address.
"""
import csv
import re
import sys

CATEGORIES = [
    "Λακκούβα ή φθορά οδοστρώματος",
    "Πρόβλημα με πεζοδρόμιο",
    "Οδοφωτισμός",
    "Φρεάτια και καθαριότητα",
    "Πράσινο και δέντρα",
    "Άλλο",
]

OWN_FILE = {"Δήμος Χαϊδαρίου": "haidari.sql", "Δήμος Παλαιού Φαλήρου": "palaiofaliro.sql", "Δήμος Πειραιώς": "piraeus.sql", "Δήμος Ραφήνας - Πικερμίου": "rafina.sql"}

SOURCES = {
    "both": "ΥΠΕΣ 14/08/2026 και ΚΕΔΕ 2024-2028",
    "ypes": "ΥΠΕΣ 14/08/2026",
    "kede": "ΚΕΔΕ 2024-2028",
}


def sql(s):
    return "'" + s.replace("'", "''") + "'"


def main(official_path, out_path, *correction_paths):
    with open(official_path, newline="") as f:
        rows = {row["name_el"]: row for row in csv.DictReader(f)}
    for path in correction_paths:
        with open(path, newline="") as f:
            for row in csv.DictReader(f):
                if row["name_el"] not in rows:
                    sys.exit(f"{path}: unknown municipality {row['name_el']!r}")
                rows[row["name_el"]].update({k: v for k, v in row.items() if v})

    values = []
    for name, row in sorted(rows.items()):
        if name in OWN_FILE:
            continue
        email = row["email_recommended"].strip().lower()
        if not re.fullmatch(r"[a-z0-9._+-]+@[a-z0-9-]+(\.[a-z0-9-]+)+", email):
            sys.exit(f"unexpected e-mail {email!r} for {name}")
        source = SOURCES.get(row["email_source"], row["email_source"])
        phone = row.get("kede_phones", "").split(";")[0].strip()
        note = f"Email του δήμου ({source})" + (f" · τηλ. {phone}" if phone else "")
        values.append(f"  ({sql(name)}, {sql(email)}, {sql(note)})")

    with open(out_path, "w") as out:
        out.write(f"""-- Report categories for every municipality without its own file ({len(values)} of {len(rows)}).
-- Generated by bin/greece/dimoi-sql.py from data/greece/dimoi_emails_official.csv; do not edit
-- by hand. Until categories are routed separately, every category goes to the municipality's
-- general address. Categories added in the admin are left alone; those listed here are
-- (re)confirmed with the address below. Where MapIt has one area for several municipalities
-- (Corfu, Kefalonia), a report goes to all of them, with FixMyStreet's note that it was sent to
-- several bodies.
BEGIN;
CREATE TEMP TABLE dimoi_emails (dimos text, email text, note text) ON COMMIT DROP;
INSERT INTO dimoi_emails VALUES
{(","+chr(10)).join(values)};

CREATE TEMP TABLE dimoi_categories (category text, sort int) ON COMMIT DROP;
INSERT INTO dimoi_categories VALUES
{(","+chr(10)).join(f"  ({sql(c)}, {i})" for i, c in enumerate(CATEGORIES))};

DO $$
DECLARE missing text;
BEGIN
  SELECT string_agg(e.dimos, ', ') INTO missing FROM dimoi_emails e
   WHERE NOT EXISTS (SELECT 1 FROM body b JOIN body_areas a ON a.body_id = b.id WHERE b.name = e.dimos AND NOT b.deleted);
  IF missing IS NOT NULL THEN RAISE EXCEPTION 'municipalities without a body or area: %', missing; END IF;
END $$;

INSERT INTO contacts (body_id, category, email, state, editor, whenedited, note)
SELECT b.id, c.category, e.email, 'confirmed', 'import', now(), e.note
  FROM dimoi_emails e JOIN body b ON b.name = e.dimos AND NOT b.deleted
 CROSS JOIN dimoi_categories c
 ORDER BY b.id, c.sort
ON CONFLICT (body_id, category) DO UPDATE
  SET email = EXCLUDED.email, note = EXCLUDED.note, state = 'confirmed', editor = 'import', whenedited = now();
COMMIT;
""")
    print(f"{len(values)} municipalities x {len(CATEGORIES)} categories written to {out_path}")


if __name__ == "__main__":
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    main(*sys.argv[1:])
